-- 005 — Gudang virtual (additive, idempotent via schema_migrations).
-- Tidak menyentuh tabel/seed yang sudah ada; migration ini hanya menambah:
--  - warehouse_locations  : tata letak gudang (zona/rak/bin). Baris template
--                           dibubung flag is_template=1 (label template, bukan
--                           fakta gudang user; layout awal bisa dikonfigurasi
--                           ulang oleh manager/admin lewat API).
--  - location_allocations : qty produk per lokasi (alokasi parsial boleh;
--                           invarian: Σ alokasi per produk <= stok nyata).
--  - warehouse_movements  : riwayat perpindahan + actor + waktu (audit).
CREATE TABLE warehouse_locations (
  id TEXT NOT NULL PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  zone TEXT NOT NULL,
  rack TEXT,
  bay INTEGER,
  label TEXT NOT NULL DEFAULT '',
  capacity INTEGER NOT NULL DEFAULT 0 CHECK (capacity >= 0),
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  sort_index INTEGER NOT NULL DEFAULT 0,
  is_template INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE location_allocations (
  location_id TEXT NOT NULL,
  product_id TEXT NOT NULL,
  qty INTEGER NOT NULL CHECK (qty >= 0),
  PRIMARY KEY (location_id, product_id),
  FOREIGN KEY (location_id) REFERENCES warehouse_locations(id),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE warehouse_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id TEXT NOT NULL,
  from_location TEXT,
  to_location TEXT,
  qty INTEGER NOT NULL CHECK (qty >= 0),
  actor_id BIGINT NOT NULL,
  reason TEXT NOT NULL,
  order_id BIGINT,
  created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  FOREIGN KEY (product_id) REFERENCES products(id),
  FOREIGN KEY (actor_id) REFERENCES users(id),
  FOREIGN KEY (from_location) REFERENCES warehouse_locations(id),
  FOREIGN KEY (to_location) REFERENCES warehouse_locations(id),
  FOREIGN KEY (order_id) REFERENCES orders(id)
);

CREATE INDEX idx_allocations_location ON location_allocations(location_id);
CREATE INDEX idx_warehouse_movements_product ON warehouse_movements(product_id, id DESC);

