CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'buyer'
    CHECK (role IN ('buyer', 'staff', 'manager', 'admin')),
  active INT NOT NULL DEFAULT 1
    CHECK (active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE sessions (
  jti TEXT NOT NULL PRIMARY KEY,
  user_id BIGINT NOT NULL,
  expires_at TEXT NOT NULL,
  revoked INT NOT NULL DEFAULT 0 CHECK (revoked IN (0, 1)),
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE categories (
  slug TEXT NOT NULL PRIMARY KEY,
  label TEXT NOT NULL
);

CREATE TABLE products (
  id TEXT NOT NULL PRIMARY KEY,
  category_slug TEXT NOT NULL,
  name TEXT NOT NULL,
  brand TEXT NOT NULL,
  price INT NOT NULL CHECK (price >= 0),
  original_price INT CHECK (
    original_price IS NULL OR original_price >= 0
  ),
  stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
  featured INT NOT NULL DEFAULT 0 CHECK (featured IN (0, 1)),
  on_sale INT NOT NULL DEFAULT 0 CHECK (on_sale IN (0, 1)),
  catalog_position INT NOT NULL DEFAULT 0 CHECK (catalog_position >= 0),
  created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  FOREIGN KEY (category_slug) REFERENCES categories(slug)
);

CREATE TABLE product_specs (
  product_id TEXT NOT NULL,
  position INT NOT NULL DEFAULT 0 CHECK (position >= 0),
  key TEXT NOT NULL,
  value TEXT NOT NULL,
  PRIMARY KEY (product_id, position),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference TEXT NOT NULL UNIQUE,
  buyer_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'shipped', 'delivered')),
  client_request_id TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  buyer_contact TEXT NOT NULL,
  shipping_address TEXT NOT NULL,
  payment_method TEXT NOT NULL,
  subtotal INT NOT NULL CHECK (subtotal >= 0),
  shipping INT NOT NULL DEFAULT 0 CHECK (shipping >= 0),
  total INT NOT NULL CHECK (total >= 0),
  created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (buyer_id, client_request_id),
  FOREIGN KEY (buyer_id) REFERENCES users(id)
);

CREATE TABLE order_lines (
  order_id BIGINT NOT NULL,
  product_id TEXT NOT NULL,
  product_name TEXT NOT NULL,
  unit_price INT NOT NULL CHECK (unit_price >= 0),
  qty INT NOT NULL CHECK (qty > 0),
  amount INT NOT NULL CHECK (amount >= 0),
  UNIQUE (order_id, product_id),
  FOREIGN KEY (order_id) REFERENCES orders(id),
  FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  product_id TEXT NOT NULL,
  buyer_id BIGINT NOT NULL,
  rating INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body TEXT NOT NULL DEFAULT '',
  -- Mirror the review states the frontend already tracks.
  state TEXT NOT NULL DEFAULT 'public' CHECK (state IN ('public', 'hidden')),
  seller_comment TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (order_id, product_id, buyer_id),
  FOREIGN KEY (order_id, product_id) REFERENCES order_lines(order_id, product_id),
  FOREIGN KEY (buyer_id) REFERENCES users(id)
);

CREATE TABLE stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id TEXT NOT NULL,
  actor_id BIGINT NOT NULL,
  delta INT NOT NULL,
  reason TEXT NOT NULL,
  order_id BIGINT,
  created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'),
  FOREIGN KEY (product_id) REFERENCES products(id),
  FOREIGN KEY (actor_id) REFERENCES users(id),
  FOREIGN KEY (order_id) REFERENCES orders(id)
);
